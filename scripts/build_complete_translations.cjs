for (const [code, dict] of Object.entries(existingT)) {
  for (const [key, enVal] of Object.entries(existingT.en)) {
    if (!dict[key]) {
      // If delta has it, use it
      if (langDeltas[code]?.[key]) {
        dict[key] = langDeltas[code][key];
      } else {
        // Fallback to English value or existing word
        dict[key] = enVal;
      }
    }
  }
}

