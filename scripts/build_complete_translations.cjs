// Build enhanced translate function
const newTranslateFunction = `/**
 * Universal translation resolver supporting all languages from A to Z with direct key & reverse English fallback lookup
 */
export function translate(langCode: string, key: string, fallback?: string): string {
  const defaultFallback = fallback !== undefined ? fallback : key;
  if (!langCode || !key) return defaultFallback;

  const targetLang = langCode.trim();
  const baseCode = targetLang.split('-')[0].toLowerCase();
  const dict = TRANSLATIONS[targetLang] || TRANSLATIONS[baseCode] || TRANSLATIONS['en'];

  const cleanKey = key.trim();
  const lowerKey = cleanKey.toLowerCase();

  if (dict) {
    // 1. Direct key match (e.g. 'chats', 'welcomeTitle')
    if (dict[cleanKey]) return dict[cleanKey];
    if (dict[lowerKey]) return dict[lowerKey];

    // 2. Case-insensitive key match
    const foundKey = Object.keys(dict).find((k) => k.toLowerCase() === lowerKey);
    if (foundKey && dict[foundKey]) return dict[foundKey];

    // 3. Reverse lookup against English dictionary values
    const enDict = TRANSLATIONS['en'];
    if (enDict) {
      const match = Object.entries(enDict).find(
        ([k, v]) => k.toLowerCase() === lowerKey || v.toLowerCase() === lowerKey
      );
      if (match && dict[match[0]]) {
        return dict[match[0]];
      }
    }
  }

  // 4. Fallback to English dictionary
  if (TRANSLATIONS['en']?.[cleanKey]) {
    return TRANSLATIONS['en'][cleanKey];
  }

  return defaultFallback;
}
`;

